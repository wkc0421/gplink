import { test, expect } from '@playwright/test'
test.use({ baseURL: 'http://127.0.0.1:5198' })
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: '模拟数据补录', exact: true }).click()
  await page.locator('.ant-select[aria-label="选择设备"]').click()
  await page.getByTitle('测试电表（test-meter）').click()
  await page.locator('.ant-select[aria-label="数值型采集项"]').click()
  await page.getByTitle('累计电量（E）· double kWh').click()
  const dates = page.locator('.ant-picker-input input')
  await dates.nth(0).click(); await dates.nth(0).fill('2025-01-01 00:00:00'); await dates.nth(0).press('Enter')
  await dates.nth(1).click(); await dates.nth(1).fill('2025-01-02 00:00:00'); await dates.nth(1).press('Enter')
  await page.getByText('模拟历史数据补录', { exact: true }).click()
})
test('single selection, preview invalidation, successful submission and query handoff', async ({ page }) => {
  await expect(page.getByText('已选择 1 / 1 个设备')).toBeVisible()
  await expect(page.getByRole('button', { name: '提交补录任务' })).toBeDisabled()
  await page.getByRole('button', { name: '检查补录参数' }).click()
  await expect(page.getByRole('button', { name: '提交补录任务' })).toBeEnabled()
  await page.getByRole('textbox', { name: '最小值', exact: true }).fill('2')
  await expect(page.getByRole('button', { name: '提交补录任务' })).toBeDisabled()
  await page.getByRole('radio', { name: '固定递增' }).check()
  await page.getByRole('textbox', { name: '初始值' }).fill('9007199254740993')
  await page.getByRole('checkbox', { name: '同时生成累计量小时／日快照' }).check()
  await page.getByRole('button', { name: '检查补录参数' }).click()
  await expect(page.getByText('9007199254740993', { exact: true })).toBeVisible()
  await expect(page.getByText('提交后启用（影响整个产品该采集项）')).toBeVisible()
  await page.getByRole('button', { name: '提交补录任务' }).click()
  await page.getByRole('button', { name: '带入统计查询' }).click()
  await expect(page.getByRole('textbox', { name: '属性 ID', exact: true })).toHaveValue('E')
  await page.getByRole('button', { name: '发送查询' }).click()
  await expect(page.getByText('状态 200')).toBeVisible()
})
test('existing data blocks submission, failure can retry and opens paged raw history', async ({ page }) => {
  await page.getByRole('textbox', { name: '最小值', exact: true }).fill('99')
  await page.getByRole('button', { name: '检查补录参数' }).click()
  await expect(page.getByRole('button', { name: '提交补录任务' })).toBeDisabled()
  await page.getByRole('textbox', { name: '最小值', exact: true }).fill('13')
  await page.getByRole('button', { name: '检查补录参数' }).click()
  await page.getByRole('button', { name: '提交补录任务' }).click()
  await expect(page.getByText('测试刷新失败')).toBeVisible()
  await page.getByRole('button', { name: '重试原任务' }).click()
  await page.getByRole('button', { name: '查看属性历史' }).click()
  await page.getByRole('button', { name: '查询历史', exact: true }).click()
  await expect(page.getByText('100.25', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
})
