import { test, expect, type Page } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:5207' })

const items = [
  { code: 'Ua', name: 'A相电压' }, { code: 'Ub', name: 'B相电压' },
  ...Array.from({ length: 22 }, (_, i) => ({ code: `Extra${i}`, name: `扩展${i}` })),
].map(item => ({ ...item, id: item.code, libraryId: 'standard', categoryId: 'voltage', enabled: true, sortIndex: 0 }))

async function setup(page: Page, target: 'product' | 'device', batchSeed = false) {
  await page.route('**/mock/device/**', async route => {
    const url = new URL(route.request().url()), body = route.request().postDataJSON?.()
    let result: any
    if (url.pathname.endsWith('/_all')) result = [{ id: 'standard', code: 'standard', name: '标准库', enabled: true, sortIndex: 0 }]
    else if (url.pathname.endsWith('/_tree')) result = [{ id: 'voltage', name: '电压', children: [] }]
    else {
      let filtered = items
      if (body?.keyword) filtered = filtered.filter(item => (item.code + item.name).toLowerCase().includes(body.keyword.toLowerCase()))
      const index = body?.pageIndex || 0, size = body?.pageSize || 20
      result = { data: filtered.slice(index * size, (index + 1) * size), total: filtered.length, pageIndex: index, pageSize: size }
    }
    await route.fulfill({ json: { success: true, status: 200, result } })
  })
  await page.goto(`/?real=${target}${batchSeed ? '&batchSeed=1' : ''}`)
  await expect(page.locator('.property-summary-table')).toBeVisible()
}

const row = (page: Page, code: string) => page.locator('.property-summary-table tbody tr').filter({ has: page.getByRole('cell', { name: code, exact: true }) })
async function addFromLibrary(page: Page, codes: string[]) {
  await page.getByRole('button', { name: '从采集项库添加' }).click()
  const picker = page.getByRole('dialog')
  for (const code of codes) await picker.getByRole('row').filter({ has: page.getByRole('cell', { name: code, exact: true }) }).getByRole('checkbox').check()
  await picker.getByRole('button', { name: '加入物模型' }).click()
}

test('search matches name and ID, preserves cross-page selection, and batch changes stay in draft after a failed save', async ({ page }) => {
  await setup(page, 'product')
  const original = await page.getByTestId('store').innerText()
  await addFromLibrary(page, ['Ub', ...Array.from({ length: 10 }, (_, i) => `Extra${i}`)])
  const table = page.locator('.property-summary-table')
  await expect(table).toContainText('共 12 项')
  await table.locator('thead').getByRole('checkbox').check()
  await table.getByTitle('2', { exact: true }).click()
  await table.locator('thead').getByRole('checkbox').check()
  await expect(page.getByText('已选 12 项', { exact: true })).toBeVisible()
  const search = page.getByRole('textbox', { name: '搜索属性名称或 ID' })
  await search.fill('extra9')
  await expect(row(page, 'Extra9')).toBeVisible()
  await expect(row(page, 'Extra8')).toHaveCount(0)
  await expect(row(page, 'Extra9').getByRole('checkbox')).toBeChecked()
  await expect(page.getByText('已选 12 项', { exact: true })).toBeVisible()
  await search.fill('原a相')
  await expect(row(page, 'Ua')).toBeVisible()
  await expect(page.getByText('已选 12 项', { exact: true })).toBeVisible()
  await search.fill('')
  await page.getByRole('button', { name: '批量设置' }).click()
  const dialog = page.getByRole('dialog', { name: '批量设置采集项' })
  await dialog.getByRole('checkbox', { name: '设置数据类型' }).check()
  await dialog.getByRole('combobox', { name: '数据类型' }).selectOption('float')
  await dialog.getByRole('checkbox', { name: '设置单位' }).check()
  await dialog.getByRole('textbox', { name: '单位' }).fill('V')
  await dialog.getByRole('button', { name: /^(确\s*定|OK)$/i }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('store')).toHaveText(original)
  await page.getByRole('button', { name: '模拟保存失败' }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  await expect(page.getByRole('status')).toContainText('保存失败')
  await expect(page.getByTestId('store')).toHaveText(original)
  const payload = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(payload.properties).toHaveLength(12)
  expect(payload.properties.every((item: any) => item.valueType.type === 'float' && item.valueType.unit === 'V')).toBe(true)
  expect(payload.properties.find((item: any) => item.id === 'Ua').expands.registerAddr).toBe('42')
  expect(payload.functions).toEqual([{ id: 'originalFunction' }])
})

