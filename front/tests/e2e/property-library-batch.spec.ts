test('same type preserves enum data and selection survives switching groups', async ({ page }) => {
  await setup(page, 'product', true)
  await row(page, 'Enum1').getByRole('checkbox').check()
  await page.getByRole('tab', { name: /第二分组/ }).click()
  await row(page, 'Other1').getByRole('checkbox').check()
  await expect(page.getByText('已选 2 项', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '批量设置' }).click()
  const dialog = page.getByRole('dialog', { name: '批量设置采集项' })
  await dialog.getByRole('checkbox', { name: '设置单位' }).check()
  await dialog.getByRole('textbox', { name: '单位' }).fill('W')
  await dialog.getByRole('button', { name: /^(确\s*定|OK)$/i }).click()
  await page.getByRole('tab', { name: /默认分组/ }).click()
  await row(page, 'Enum1').getByRole('checkbox').check()
  await page.getByRole('button', { name: '批量设置' }).click()
  await dialog.getByRole('checkbox', { name: '设置数据类型' }).check()
  await dialog.getByRole('combobox', { name: '数据类型' }).selectOption('enum')
  await dialog.getByRole('button', { name: /^(确\s*定|OK)$/i }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  await expect(page.getByRole('status')).toContainText('保存成功')
  const payload = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  const item = payload.properties.find((value: any) => value.id === 'Enum1')
  expect(item.valueType.elements).toEqual([{ text: '开', value: 'on' }])
  expect(item.valueType.unit).toBe('W')
  expect(item.expands.metrics).toEqual([{ id: 'keep' }])
  expect(item.expands.registerAddr).toBe('77')
  expect(payload.properties.find((value: any) => value.id === 'Other1').valueType.unit).toBe('W')
  expect(payload.properties.find((value: any) => value.id === 'Ua').valueType.unit).toBe('V')
})

