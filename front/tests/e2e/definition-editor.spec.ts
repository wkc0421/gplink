test('事件的新增和修改限制分别生效', async ({ page }) => {
  await page.goto('/?real=device&type=events&definitionSeed=1&eventLimit=eventNotInsertable')
  let row = page.locator('.definition-summary-table tbody tr').filter({ hasText: 'alarm' })
  await expect(page.getByRole('button', { name: '新增事件' })).toBeDisabled()
  await expect(row.getByRole('button', { name: '复制' })).toBeDisabled()
  await expect(row.getByRole('button', { name: '编辑' })).toBeEnabled()
  await page.goto('/?real=device&type=events&definitionSeed=1&eventLimit=eventNotModifiable')
  row = page.locator('.definition-summary-table tbody tr').filter({ hasText: 'alarm' })
  await expect(page.getByRole('button', { name: '新增事件' })).toBeEnabled()
  await expect(row.getByRole('button', { name: '复制' })).toBeEnabled()
  await expect(row.getByRole('button', { name: '编辑' })).toBeDisabled()
  await expect(row.getByRole('button', { name: '删除' })).toBeDisabled()
})

test('复制标签要求新 ID 并保留原项', async ({ page }) => {
  await page.goto('/?real=product&type=tags&definitionSeed=1')
  const table = page.locator('.definition-summary-table')
  await table.locator('tbody tr').filter({ hasText: 'location' }).getByRole('button', { name: '复制' }).click()
  const modal = page.getByRole('dialog', { name: '新增标签' })
  await modal.getByLabel('标签 ID').fill('location')
  await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await expect(modal).toContainText('标签 ID 已存在')
  await modal.getByLabel('标签 ID').fill('location_copy')
  await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
  const rows = table.locator('tbody tr')
  await expect(rows.filter({ hasText: 'location' })).toHaveCount(2)
  await page.getByRole('button', { name: '保存物模型' }).click()
  const saved = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(saved.tags).toHaveLength(2)
  expect(saved.tags[0].id).not.toBe(saved.tags[1].id)
  expect(saved.tags[0].expands.keep).toBe('tag-extra')
  expect(saved.tags[1].expands.keep).toBe('tag-extra')
})

test('功能字符串长度可修改并在再次打开时保留，其他配置不丢失', async ({ page }) => {
  await page.goto('/?real=product&type=functions&definitionSeed=1')
  const row = page.locator('.definition-summary-table tbody tr').filter({ hasText: 'reboot' })
  await row.getByRole('button', { name: '编辑' }).click()
  const modal = page.getByRole('dialog', { name: '编辑功能' })
  await modal.locator('.type-control button').click()
  const popover = page.locator('.ant-popover:visible')
  const maxLength = popover.getByRole('spinbutton')
  await expect(maxLength).toHaveValue('32')
  await maxLength.fill('48')
  await popover.getByRole('button', { name: /确\s*认/ }).click()
  await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await row.getByRole('button', { name: '编辑' }).click()
  await modal.locator('.type-control button').click()
  await expect(page.locator('.ant-popover:visible').getByRole('spinbutton')).toHaveValue('48')
  await page.locator('.ant-popover:visible').getByRole('button', { name: /取\s*消/ }).click()
  await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  const saved = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(saved.functions[0].output.expands.keep).toBe('output-extra')
  expect(saved.functions[0].inputs[0].id).toBe('delay')
})

