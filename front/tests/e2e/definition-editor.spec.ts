import { test, expect } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:5213' })

const cases = [
  { type: 'functions', label: '功能', id: 'reboot', name: '重启', other: 'function-extra' },
  { type: 'events', label: '事件', id: 'alarm', name: '告警', other: 'event-extra' },
  { type: 'tags', label: '标签', id: 'location', name: '位置', other: 'tag-extra' },
] as const

for (const item of cases) {
  test(`${item.label}编辑取消保留数据，确认只改草稿，保存保留其他字段`, async ({ page }) => {
    await page.goto(`/?real=product&type=${item.type}&definitionSeed=1`)
    const table = page.locator('.definition-summary-table')
    const row = table.locator('tbody tr').filter({ hasText: item.id })
    await expect(row).toContainText(item.name)
    const before = await page.getByTestId('store').innerText()
    await row.getByRole('button', { name: '编辑' }).click()
    const modal = page.getByRole('dialog', { name: `编辑${item.label}` })
    await modal.getByLabel(`${item.label}名称`).fill('取消的修改')
    await modal.getByRole('button', { name: /^(取消|Cancel)$/i }).click()
    await expect(row).toContainText(item.name)
    await row.getByRole('button', { name: '编辑' }).click()
    await modal.getByLabel(`${item.label}名称`).fill('新的名称')
    await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
    await expect(row).toContainText('新的名称')
    await expect(page.getByTestId('store')).toHaveText(before)
    await page.getByRole('button', { name: '保存物模型' }).click()
    const payload = JSON.parse((await page.getByTestId('payload').innerText()) || '{}')
    const saved = JSON.parse(payload.metadata)
    expect(saved[item.type][0].name).toBe('新的名称')
    expect(saved[item.type][0].expands.keep).toBe(item.other)
  })

  test(`${item.label}继承记录不可修改`, async ({ page }) => {
    await page.goto(`/?real=device&type=${item.type}&definitionSeed=1`)
    const row = page.locator('.definition-summary-table tbody tr').filter({ hasText: item.id })
    await expect(row).toContainText(item.name)
    await expect(row.getByRole('button', { name: '编辑' })).toBeDisabled()
    await expect(row.getByRole('button', { name: '复制' })).toBeDisabled()
    await expect(row.getByRole('button', { name: '删除' })).toBeDisabled()
  })
}

