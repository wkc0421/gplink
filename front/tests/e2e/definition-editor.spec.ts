test('事件嵌套输出参数可编辑，取消弹窗不污染原数据', async ({ page }) => {
  await page.goto('/?real=product&type=events&definitionSeed=1')
  const row = page.locator('.definition-summary-table tbody tr').filter({ hasText: 'alarm' })
  await row.getByRole('button', { name: '编辑' }).click()
  const modal = page.getByRole('dialog', { name: '编辑事件' })
  await modal.getByRole('button', { name: '配置输出参数（1）' }).click()
  const popup = page.locator('.ant-popover:visible').filter({ has: page.locator('input[value="level"]') })
  await popup.locator('input[value="级别"]').fill('严重程度')
  await popup.getByRole('button', { name: /确\s*认/ }).click()
  await modal.getByRole('button', { name: /^(取消|Cancel)$/i }).click()
  expect(JSON.parse(await page.getByTestId('store').innerText()).events[0].valueType.properties[0].name).toBe('级别')
  await row.getByRole('button', { name: '编辑' }).click()
  await modal.getByRole('button', { name: '配置输出参数（1）' }).click()
  const popup2 = page.locator('.ant-popover:visible').filter({ has: page.locator('input[value="level"]') })
  await expect(popup2.locator('input[value="级别"]')).toBeVisible()
  await popup2.locator('input[value="级别"]').fill('严重程度')
  await popup2.getByRole('button', { name: /确\s*认/ }).click()
  await modal.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  const saved = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(saved.events[0].valueType.properties[0].name).toBe('严重程度')
  expect(saved.events[0].expands.keep).toBe('event-extra')
})


