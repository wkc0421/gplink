import { test, expect } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:5214' })

test('枚举项可新增、编辑、确认和取消', async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?real=product&batchSeed=1')
  const row = page.locator('.property-summary-table tbody tr').filter({ hasText: 'Enum1' })
  await row.getByRole('button', { name: '编辑' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑采集项' })
  await dialog.locator('.type-control button').click({ timeout: 6000 })
  const popup = page.locator('.ant-popover:visible')
  await popup.getByRole('button', { name: /新增枚举项/ }).click()
  const inputs = popup.locator('.metadata-edit-table-body input')
  await expect(inputs).toHaveCount(4)
  await inputs.nth(2).fill('off')
  await inputs.nth(3).fill('关')
  await popup.getByRole('button', { name: /确\s*认/ }).click()
  await dialog.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await row.getByRole('button', { name: '编辑' }).click()
  await dialog.locator('.type-control button').click()
  const reopened = page.locator('.ant-popover:visible')
  await expect(reopened.locator('.metadata-edit-table-body input')).toHaveCount(4)
  await expect(reopened.locator('input').nth(2)).toHaveValue('off')
  await reopened.locator('input').nth(2).fill('cancelled')
  await reopened.getByRole('button', { name: /取\s*消/ }).click()
  await dialog.locator('.type-control button').click()
  await expect(page.locator('.ant-popover:visible input').nth(2)).toHaveValue('off')
  await page.locator('.ant-popover:visible').getByRole('button', { name: /取\s*消/ }).click()
  await dialog.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  const saved = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(saved.properties.find((item: any) => item.id === 'Enum1').valueType.elements).toEqual([
    { value: 'on', text: '开' }, { value: 'off', text: '关' },
  ])
  expect(errors).toEqual([])
})

test('小视口下空枚举可以新增并逐字输入', async ({ page }) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width: 740, height: 350 })
  await page.goto('/?real=product')
  const row = page.locator('.property-summary-table tbody tr').filter({ hasText: 'Ua' })
  await row.getByRole('button', { name: '编辑' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑采集项' })
  await dialog.locator('.type-control .ant-select-selector').click()
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: 'enum(' }).click()
  await dialog.locator('.type-control button').click()
  const popup = page.locator('.ant-popover:visible')
  await popup.getByRole('button', { name: /新增枚举项/ }).click()
  const inputs = popup.locator('.metadata-edit-table-body input')
  await expect(inputs).toHaveCount(2)
  const box = await inputs.first().boundingBox()
  console.log('350px viewport popover', await popup.boundingBox(), 'first enum input', box)
  expect(box).not.toBeNull()
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(350)
  await inputs.first().pressSequentially('offline', { delay: 30 })
  await inputs.nth(1).pressSequentially('Offline', { delay: 30 })
  await expect(inputs.first()).toHaveValue('offline')
  await expect(inputs.nth(1)).toHaveValue('Offline')
  await popup.getByRole('button', { name: /确\s*认/ }).click()
  await dialog.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await row.getByRole('button', { name: '编辑' }).click()
  await dialog.locator('.type-control button').click()
  await expect(page.locator('.ant-popover:visible input').first()).toHaveValue('offline')
  await page.locator('.ant-popover:visible').getByRole('button', { name: /取\s*消/ }).click()
  await dialog.getByRole('button', { name: /^(确定|OK)$/i }).click()
  await page.getByRole('button', { name: '保存物模型' }).click()
  const saved = JSON.parse(JSON.parse(await page.getByTestId('payload').innerText()).metadata)
  expect(saved.properties.find((item: any) => item.id === 'Ua').valueType.elements).toEqual([{ value: 'offline', text: 'Offline' }])
})

test('枚举空值和重复值不允许确认，取消恢复原值', async ({ page }) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width: 740, height: 503 })
  await page.goto('/?real=product&batchSeed=1')
  const row = page.locator('.property-summary-table tbody tr').filter({ hasText: 'Enum1' })
  await row.getByRole('button', { name: '编辑' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑采集项' })
  await dialog.locator('.type-control button').click()
  let popup = page.locator('.ant-popover:visible')
  await popup.getByRole('button', { name: /新增枚举项/ }).click()
  let inputs = popup.locator('.metadata-edit-table-body input')
  await expect(inputs).toHaveCount(4)
  await popup.getByRole('button', { name: /确\s*认/ }).click()
  await expect(popup).toBeVisible()
  await expect(inputs.nth(2).locator('..')).toHaveClass(/edit-table-form-has-error/)
  await expect(inputs.nth(3).locator('..')).toHaveClass(/edit-table-form-has-error/)
  await inputs.nth(2).fill('on')
  await inputs.nth(3).fill('重复')
  await popup.getByRole('button', { name: /确\s*认/ }).click()
  await expect(popup).toBeVisible()
  await expect(inputs.nth(2).locator('..')).toHaveClass(/edit-table-form-has-error/)
  await popup.getByRole('button', { name: /取\s*消/ }).click()
  await dialog.locator('.type-control button').click()
  popup = page.locator('.ant-popover:visible')
  inputs = popup.locator('.metadata-edit-table-body input')
  await expect(inputs).toHaveCount(2)
  await expect(inputs.first()).toHaveValue('on')
  await inputs.first().fill('changed')
  await popup.getByRole('button', { name: /取\s*消/ }).click()
  await dialog.locator('.type-control button').click()
  await expect(page.locator('.ant-popover:visible .metadata-edit-table-body input').first()).toHaveValue('on')
})
