test('single device rebuild and cancellation keep device task identity', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: '设备实际生效' }).click()
  await row(page, '累计电量').getByRole('button', { name: '回填 / 重算', exact: true }).click()
  const rebuild = page.getByRole('dialog', { name: '历史回填 / 范围重算' })
  await rebuild.getByPlaceholder('开始时间').click()
  await rebuild.getByPlaceholder('开始时间').fill('2026-10-01 00:00:00')
  await rebuild.getByPlaceholder('开始时间').press('Enter')
  await rebuild.getByPlaceholder('结束时间').click()
  await rebuild.getByPlaceholder('结束时间').fill('2026-10-02 00:00:00')
  await rebuild.getByPlaceholder('结束时间').press('Enter')
  await rebuild.getByRole('button', { name: '提交任务' }).click()
  const task = page.getByRole('dialog', { name: '历史统计任务' })
  await expect(task).toContainText('new-task')
  expect(await page.evaluate(() => (window as any).__historyFixture.calls.filter((v: any) => v.path.endsWith('/_rebuild')))).toEqual([expect.objectContaining({ path: '/device/history-statistics/device/d1/E/_rebuild', body: { from: Date.UTC(2026, 8, 30, 16), to: Date.UTC(2026, 9, 1, 16) } })])
  await task.getByRole('button', { name: '取消后续处理' }).click()
  await expect(task).toContainText('已取消')
  expect(await page.evaluate(() => (window as any).__historyFixture.calls.some((v: any) => v.path === '/device/history-statistics/device/d1/tasks/new-task/_cancel'))).toBe(true)
})

