import { expect, test, type Page } from '@playwright/test'
test.use({ baseURL: 'http://127.0.0.1:5217' })
const row = (page: Page, name: string) => page.locator('.history-table tbody tr').filter({ has: page.getByText(name, { exact: true }) })
async function target(page: Page, label: string, name: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: name }).click()
  await page.getByRole('combobox', { name: label, exact: true }).press('Tab')
}
test('product paging and multi-product add preserve full identity and retry only failed items', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.history-table')).toContainText('共 22 项')
  await page.locator('.history-table tbody tr.ant-table-row').first().getByRole('checkbox').check()
  await page.locator('.history-table').getByTitle('2', { exact: true }).click()
  await expect(page.locator('.history-table tbody tr.ant-table-row')).toHaveCount(2)
  await page.locator('.history-table tbody tr.ant-table-row').first().getByRole('checkbox').check()
  await expect(page.getByText('已选择 2 项', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '批量新增产品默认', exact: true }).click()
  const drawer = page.locator('.history-add-drawer')
  await target(page, '选择产品', '电表产品')
  await target(page, '选择产品', '水表产品')
  const search = page.getByRole('textbox', { name: '搜索待新增采集项' })
  await search.fill('X'); await search.press('Enter')
  await expect(page.locator('.candidate-table tbody tr.ant-table-row')).toHaveCount(2)
  await page.locator('.candidate-table thead').getByRole('checkbox').check()
  await page.evaluate(() => (window as any).__historyFixture.failures.add('p2/X'))
  await drawer.getByRole('button', { name: '启用所选 2 项' }).click()
  await expect(drawer).toContainText('水表产品 / 备用水量（X）：模拟项目失败')
  await expect(drawer.getByRole('button', { name: '启用所选 1 项' })).toBeEnabled()
  await drawer.getByRole('button', { name: '启用所选 1 项' }).click()
  await expect(drawer).not.toHaveClass(/ant-drawer-open/)
  const batches = await page.evaluate(() => (window as any).__historyFixture.calls.filter((v: any) => v.path.endsWith('/_batch')).map((v: any) => v.body.items))
  expect(batches[0].map((v: any) => [v.productId, v.propertyId])).toEqual([['p1', 'X'], ['p2', 'X']])
  expect(batches[1]).toHaveLength(1); expect(batches[1][0].productId).toBe('p2')
})
test('device removal creates an exception and restore inheritance follows the product default', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: '设备实际生效' }).click()
  await row(page, '累计电量').getByRole('button', { name: '移除统计', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '移除历史统计' })
  await expect(dialog).toContainText('设备设置停用例外')
  await dialog.getByRole('button', { name: /确\s*定/ }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: '仅看设备例外' }).click()
  await expect(row(page, '累计电量')).toContainText('设备单独停用')
  await row(page, '累计电量').getByRole('button', { name: '恢复继承', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '恢复产品默认' })
  await expect(dialog).toContainText('预计启用 1 项、停用 0 项')
  await dialog.getByRole('button', { name: /确\s*定/ }).click()
  await expect(dialog).toBeHidden()
  await expect(row(page, '累计电量')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).__historyFixture.overrides.has('d1/E'))).toBe(false)
})
